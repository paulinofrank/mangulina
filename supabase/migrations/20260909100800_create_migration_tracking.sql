-- Fix: list_migrations returned an empty array. The entire schema -- 100+
-- tables, ~100 functions, every RLS policy -- existed with zero tracked
-- migrations.
--
-- The cause is not that migrations were never written. This repo holds 449 pre-existing
-- migration files under supabase/migrations/ across 231 commits, plus the nine
-- added in this batch. They were applied with direct psql (scripts/runSqlFile.ts over DATABASE_URL) rather
-- than through the Supabase CLI, and only the CLI writes to
-- supabase_migrations.schema_migrations. That schema did not exist at all.
--
-- This migration creates the tracking table the CLI expects and reconciles it
-- with the files already applied, so that list_migrations, schema diffing and
-- `supabase db push` all work from here on.
--
-- Important: this is a RECONCILIATION, not a replay. It asserts that the live
-- schema already contains the effect of these files. It does not execute them.
-- drop_legacy_subgenres_table.sql is deliberately excluded: it has no version
-- prefix and is a pending manual step, not an applied migration.

